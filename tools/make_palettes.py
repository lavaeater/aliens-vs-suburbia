#!/usr/bin/env python3
"""Generate the bigger retro palettes in assets/palettes/ (docs/retro-look.md).

Each palette is a set of ramps, dark to light, laid out evenly in OKLab lightness. Like
hand-made pixel-art ramps, shadows lean towards blue and highlights towards yellow
(`shift`), and chroma eases off at both ends. Colours outside sRGB lose chroma until
they fit. Run from the project root: python3 tools/make_palettes.py
"""

import math
import os

OUT = "assets/palettes"
COOL, WARM = 265.0, 85.0  # OKLCh hues shadows and highlights lean towards


def oklab_to_srgb(L, a, b):
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_ ** 3, m_ ** 3, s_ ** 3
    rgb = (
        4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
        -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
        -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s,
    )
    return rgb


def in_gamut(rgb):
    return all(-1e-4 <= c <= 1 + 1e-4 for c in rgb)


def encode(c):
    c = min(max(c, 0.0), 1.0)
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def lch(L, C, h):
    """OKLCh to hex, reducing chroma until it is in sRGB."""
    while True:
        rgb = oklab_to_srgb(L, C * math.cos(math.radians(h)), C * math.sin(math.radians(h)))
        if in_gamut(rgb) or C <= 0.0:
            return "".join(f"{round(encode(c) * 255):02x}" for c in rgb)
        C -= 0.002


def lean(h, towards, amount):
    """Turn hue `h` part of the way towards `towards`, the short way round."""
    d = (towards - h + 180.0) % 360.0 - 180.0
    return h + d * amount


def ramp(hue, chroma, steps, lo=0.12, hi=0.93, shift=0.25):
    out = []
    for i in range(steps):
        t = i / (steps - 1) if steps > 1 else 0.5
        L = lo + (hi - lo) * t
        h = lean(hue, COOL, shift * (1 - 2 * t)) if t < 0.5 else lean(hue, WARM, shift * (2 * t - 1))
        C = chroma * (1.0 - 0.55 * (2 * t - 1) ** 2)
        out.append(lch(L, C, h % 360.0))
    return out


# (hue, chroma) per ramp. Greys carry a little blue so night shadows stay cool.
SUBURB = [
    (255, 0.025),  # blue-grey: night, asphalt, concrete
    (250, 0.10),   # sky / moonlit blue
    (140, 0.12),   # lawn green
    (110, 0.09),   # olive / hedges
    (35, 0.13),    # brick red
    (60, 0.12),    # sodium lamp orange / wood
    (90, 0.12),    # warm yellow light
    (195, 0.10),   # teal / pool water
    (320, 0.11),   # purple / alien
    (50, 0.07),    # skin
]

DRIFTER = [
    (290, 0.04),   # violet greys
    (275, 0.14),   # deep blue-violet
    (330, 0.20),   # magenta
    (10, 0.18),    # hot pink
    (45, 0.13),    # peach
    (185, 0.13),   # teal
    (160, 0.12),   # mint
    (95, 0.12),    # pale gold
]

MOEBIUS = [
    (70, 0.02),    # paper greys
    (230, 0.06),   # pale sky
    (200, 0.05),   # sea glass
    (130, 0.06),   # sage
    (75, 0.08),    # sand
    (45, 0.09),    # terracotta
    (15, 0.07),    # dusty rose
    (300, 0.06),   # lilac shadow
]


# The 128-colour sets: the ramps above plus the in-between hues, 16 ramps x 8.
SUBURB_WIDE = SUBURB + [
    (285, 0.08),   # violet shadow (the Giraud night)
    (220, 0.07),   # slate
    (165, 0.09),   # spring green
    (20, 0.10),    # rust
    (75, 0.05),    # dry grass / sand
    (0, 0.15),     # alarm red
]

MOEBIUS_WIDE = MOEBIUS + [
    (285, 0.09),   # violet night
    (255, 0.05),   # steel blue
    (170, 0.05),   # pale jade
    (100, 0.06),   # moss
    (55, 0.14),    # hazmat orange
    (30, 0.10),    # red clay
    (330, 0.06),   # mauve
    (90, 0.04),    # bone
]


def palette(ramps, steps, **kw):
    colours = []
    for hue, chroma in ramps:
        for c in ramp(hue, chroma, steps, **kw):
            if c not in colours:
                colours.append(c)
    return colours


def write(name, colours, comment):
    path = os.path.join(OUT, f"{name}.hex")
    with open(path, "w") as f:
        f.write(f"; {comment} - generated by tools/make_palettes.py\n")
        f.write("\n".join(colours) + "\n")
    print(f"{path}: {len(colours)} colours")


if __name__ == "__main__":
    write("suburb-30", palette(SUBURB, 3), "10 suburban ramps x 3")
    write("suburb-50", palette(SUBURB, 5), "10 suburban ramps x 5")
    write("suburb-80", palette(SUBURB, 8, lo=0.08, hi=0.96), "10 suburban ramps x 8")
    write("suburb-128", palette(SUBURB_WIDE, 8, lo=0.08, hi=0.96), "16 suburban ramps x 8")
    write("moebius-128", palette(MOEBIUS_WIDE, 8, lo=0.14, hi=0.97, shift=0.3), "16 pastel ramps x 8")
    write("drifter-32", palette(DRIFTER, 4, lo=0.14, hi=0.92, shift=0.15), "neon ramps x 4")
    write("drifter-48", palette(DRIFTER, 6, lo=0.10, hi=0.94, shift=0.15), "neon ramps x 6")
    write("moebius-40", palette(MOEBIUS, 5, lo=0.22, hi=0.96, shift=0.3), "pastel ramps x 5")
    write("moebius-64", palette(MOEBIUS, 8, lo=0.16, hi=0.97, shift=0.3), "pastel ramps x 8")
